import AVFoundation
import CoreMedia
import ImageIO
import UniformTypeIdentifiers

/// Errors thrown by the pairing engine.
enum PairingError: LocalizedError {
    case cannotOpenImage
    case cannotDetermineImageType
    case cannotCreateImageDestination
    case imageWriteFailed
    case noVideoTrack
    case cannotCreateReader
    case cannotCreateWriter
    case readerFailed(String)
    case writerFailed(String)

    var errorDescription: String? {
        switch self {
        case .cannotOpenImage: return "Cannot open the image file."
        case .cannotDetermineImageType: return "Cannot determine the image type."
        case .cannotCreateImageDestination: return "Cannot create the output image."
        case .imageWriteFailed: return "Failed to write the output image."
        case .noVideoTrack: return "The video file contains no video track."
        case .cannotCreateReader: return "Cannot create an asset reader for the video."
        case .cannotCreateWriter: return "Cannot create an asset writer for the output video."
        case .readerFailed(let m): return "Asset reader failed: \(m)"
        case .writerFailed(let m): return "Asset writer failed: \(m)"
        }
    }
}

/// The core Live Photo pairing engine.
///
/// Based on analysis of genuine iPhone Live Photos:
///
/// - **HEIC/photo side**: the Apple MakerNote (EXIF) tag `0x11` ("ContentIdentifier")
///   holds a UUID, e.g. `B0C8F762-32B9-4024-AA39-B1B94E631148`.
/// - **MOV side**: the QuickTime `mdta` metadata item
///   `com.apple.quicktime.content.identifier` holds the *same* UUID.
///   This shared identifier is what pairs the two files into one Live Photo.
/// - The MOV additionally carries:
///   - `com.apple.quicktime.live-photo.auto` = 1
///   - `com.apple.quicktime.live-photo.vitality-score` / `…-scoring-version`
///   - `com.apple.quicktime.full-frame-rate-playback-intent` = 1
///   - a timed metadata track whose sample carries
///     `mdta/com.apple.quicktime.still-image-time` (int8 = -1 / 0xFF),
///     marking the video frame that corresponds to the still photo.
enum LivePhotoPairingEngine {

    // MARK: - Public API

    struct PairingOptions {
        /// UUID shared by both files. Generated by the caller.
        var contentIdentifier: String
        /// Presentation time of the "still" frame inside the video.
        var stillImageTime: CMTime
        /// Optional creation date written to the video's `com.apple.quicktime.creationdate`.
        var creationDate: Date?
    }

    struct PairingResult: Sendable {
        let photoURL: URL
        let videoURL: URL
    }

    /// Pairs a photo (HEIC/JPEG) with a video (MOV/MP4) into a Live Photo pair.
    ///
    /// The original files are never modified; new files are written next to the
    /// requested output URLs.
    static func pair(
        photo photoURL: URL,
        video videoURL: URL,
        outputPhotoURL: URL,
        outputVideoURL: URL,
        options: PairingOptions,
        progress: @escaping @Sendable (Double) -> Void
    ) async throws -> PairingResult {
        try writePhotoMetadata(
            imageURL: photoURL,
            outputURL: outputPhotoURL,
            contentIdentifier: options.contentIdentifier
        )
        progress(0.35)
        try await writeVideoMetadata(
            videoURL: videoURL,
            outputURL: outputVideoURL,
            options: options,
            progress: { p in progress(0.35 + p * 0.65) }
        )
        return PairingResult(photoURL: outputPhotoURL, videoURL: outputVideoURL)
    }

    // MARK: - Photo (HEIC) side

    /// Injects the Apple MakerNote `ContentIdentifier` (tag 17 / 0x11) into a photo
    /// using ImageIO, preserving all other metadata.
    static func writePhotoMetadata(
        imageURL: URL,
        outputURL: URL,
        contentIdentifier: String
    ) throws {
        guard let source = CGImageSourceCreateWithURL(imageURL as CFURL, nil) else {
            throw PairingError.cannotOpenImage
        }
        guard let uti = CGImageSourceGetType(source) else {
            throw PairingError.cannotDetermineImageType
        }

        var metadata =
            (CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [String: Any]) ?? [:]

        var makerApple =
            metadata[kCGImagePropertyMakerAppleDictionary as String] as? [String: Any] ?? [:]
        // Apple MakerNote tag 0x11 (17) = ContentIdentifier. ImageIO exposes the
        // MakerNote Apple dictionary with stringified tag numbers as keys.
        makerApple["17"] = contentIdentifier
        metadata[kCGImagePropertyMakerAppleDictionary as String] = makerApple

        guard let destination = CGImageDestinationCreateWithURL(
            outputURL as CFURL, uti, 1, nil
        ) else {
            throw PairingError.cannotCreateImageDestination
        }
        CGImageDestinationAddImageFromSource(destination, source, 0, metadata as CFDictionary)
        guard CGImageDestinationFinalize(destination) else {
            throw PairingError.imageWriteFailed
        }
    }

    /// Reads the existing Apple MakerNote `ContentIdentifier` of a photo, if any.
    static func readPhotoContentIdentifier(imageURL: URL) -> String? {
        guard let source = CGImageSourceCreateWithURL(imageURL as CFURL, nil),
              let metadata = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [String: Any],
              let makerApple = metadata[kCGImagePropertyMakerAppleDictionary as String] as? [String: Any]
        else { return nil }
        return makerApple["17"] as? String
    }

    // MARK: - Video (MOV) side

    /// Rewrites a QuickTime movie via lossless sample-buffer passthrough, adding the
    /// Live Photo metadata:
    ///
    /// - file-level `mdta` items: content identifier, live-photo.auto, vitality
    ///   score/version, full-frame-rate-playback-intent
    /// - a timed metadata track with a `still-image-time` sample
    static func writeVideoMetadata(
        videoURL: URL,
        outputURL: URL,
        options: PairingOptions,
        progress: @escaping @Sendable (Double) -> Void
    ) async throws {
        try await withCheckedThrowingContinuation { (continuation: CheckedContinuation<Void, Error>) in
            DispatchQueue.global(qos: .userInitiated).async {
                do {
                    try performVideoRewrite(
                        videoURL: videoURL,
                        outputURL: outputURL,
                        options: options,
                        progress: progress
                    )
                    continuation.resume()
                } catch {
                    continuation.resume(throwing: error)
                }
            }
        }
    }

    private static func performVideoRewrite(
        videoURL: URL,
        outputURL: URL,
        options: PairingOptions,
        progress: @escaping @Sendable (Double) -> Void
    ) throws {
        let asset = AVURLAsset(url: videoURL)

        guard let videoTrack = asset.tracks(withMediaType: .video).first else {
            throw PairingError.noVideoTrack
        }
        let audioTrack = asset.tracks(withMediaType: .audio).first
        let duration = asset.duration
        let durationSeconds = duration.seconds

        // MARK: Reader
        guard let reader = try? AVAssetReader(asset: asset) else {
            throw PairingError.cannotCreateReader
        }

        // nil output settings = compressed passthrough (no re-encode).
        let videoOutput = AVAssetReaderTrackOutput(track: videoTrack, outputSettings: nil)
        videoOutput.alwaysCopiesSampleData = false
        reader.add(videoOutput)

        var audioOutput: AVAssetReaderTrackOutput?
        if let audioTrack {
            let output = AVAssetReaderTrackOutput(track: audioTrack, outputSettings: nil)
            output.alwaysCopiesSampleData = false
            reader.add(output)
            audioOutput = output
        }

        // MARK: Writer
        let fm = FileManager.default
        if fm.fileExists(atPath: outputURL.path) {
            try fm.removeItem(at: outputURL)
        }
        guard let writer = try? AVAssetWriter(outputURL: outputURL, fileType: .mov) else {
            throw PairingError.cannotCreateWriter
        }

        // AVAssetTrack.formatDescriptions is typed [Any]; force-cast to the CF type.
        let videoHint = videoTrack.formatDescriptions.first.map { $0 as! CMFormatDescription }
        let videoInput = AVAssetWriterInput(
            mediaType: .video,
            outputSettings: nil,
            sourceFormatHint: videoHint
        )
        videoInput.transform = videoTrack.preferredTransform
        writer.add(videoInput)

        var audioInput: AVAssetWriterInput?
        if let audioTrack {
            let audioHint = audioTrack.formatDescriptions.first.map { $0 as! CMFormatDescription }
            let input = AVAssetWriterInput(
                mediaType: .audio,
                outputSettings: nil,
                sourceFormatHint: audioHint
            )
            writer.add(input)
            audioInput = input
        }

        // Still-image-time timed metadata track.
        let stillAdaptor = makeStillImageTimeAdaptor()
        if let stillAdaptor, writer.canAdd(stillAdaptor.assetWriterInput) {
            writer.add(stillAdaptor.assetWriterInput)
        }

        // File-level (mdta) metadata.
        writer.metadata = makeLivePhotoMetadataItems(options: options)

        guard reader.startReading() else {
            throw PairingError.readerFailed(reader.error?.localizedDescription ?? "unknown")
        }
        guard writer.startWriting() else {
            throw PairingError.writerFailed(writer.error?.localizedDescription ?? "unknown")
        }
        writer.startSession(atSourceTime: .zero)

        // MARK: Passthrough copy
        // Offset all timestamps so the earliest sample lands at t = 0.
        var timeOffset: CMTime?
        var appendedStillImageTime = false

        func shifted(_ buffer: CMSampleBuffer) -> CMSampleBuffer? {
            guard let offset = timeOffset, offset > .zero else { return buffer }
            var count: CMItemCount = 0
            CMSampleBufferGetSampleTimingInfoArray(
                buffer, entryCount: 0, arrayToFill: nil, entriesNeededOut: &count
            )
            var timing = [CMSampleTimingInfo](
                repeating: CMSampleTimingInfo(), count: Int(count)
            )
            CMSampleBufferGetSampleTimingInfoArray(
                buffer, entryCount: count, arrayToFill: &timing, entriesNeededOut: nil
            )
            for i in timing.indices {
                timing[i].presentationTimeStamp = timing[i].presentationTimeStamp - offset
                timing[i].decodeTimeStamp = timing[i].decodeTimeStamp == .invalid
                    ? .invalid : timing[i].decodeTimeStamp - offset
            }
            var out: CMSampleBuffer?
            CMSampleBufferCreateCopyWithNewTiming(
                allocator: nil,
                sampleBuffer: buffer,
                sampleTimingEntryCount: count,
                sampleTimingArray: timing,
                sampleBufferOut: &out
            )
            return out
        }

        let group = DispatchGroup()
        let queue = DispatchQueue(label: "pairing.writer")
        var copyError: Error?

        func copyTrack(output: AVAssetReaderTrackOutput, input: AVAssetWriterInput) {
            group.enter()
            input.requestMediaDataWhenReady(on: queue) {
                while input.isReadyForMoreMediaData {
                    guard let buffer = output.copyNextSampleBuffer() else {
                        input.markAsFinished()
                        group.leave()
                        return
                    }
                    let pts = CMSampleBufferGetPresentationTimeStamp(buffer)
                    if timeOffset == nil { timeOffset = pts }
                    let out = shifted(buffer) ?? buffer
                    if !input.append(out) {
                        copyError = writer.error
                        input.markAsFinished()
                        group.leave()
                        return
                    }
                    let p = min(max(pts.seconds / max(durationSeconds, 0.001), 0), 1)
                    progress(p)

                    // Append the still-image-time sample once the video passes the
                    // requested still time, so the metadata sample is ordered.
                    if !appendedStillImageTime,
                       let stillAdaptor,
                       pts >= options.stillImageTime {
                        appendedStillImageTime = true
                        appendStillImageTimeSample(
                            adaptor: stillAdaptor,
                            at: options.stillImageTime - (timeOffset ?? .zero)
                        )
                    }
                }
            }
        }

        copyTrack(output: videoOutput, input: videoInput)
        if let audioOutput, let audioInput {
            copyTrack(output: audioOutput, input: audioInput)
        }

        group.wait()
        if let copyError { throw copyError }

        // If the video never reached the requested still time (shouldn't happen
        // because the UI clamps it), append at time zero.
        if !appendedStillImageTime, let stillAdaptor {
            appendStillImageTimeSample(adaptor: stillAdaptor, at: .zero)
        }
        stillAdaptor?.assetWriterInput.markAsFinished()

        let semaphore = DispatchSemaphore(value: 0)
        writer.finishWriting {
            semaphore.signal()
        }
        semaphore.wait()

        guard writer.status == .completed else {
            throw PairingError.writerFailed(writer.error?.localizedDescription ?? "unknown")
        }
        guard reader.status == .completed || reader.status == .reading else {
            throw PairingError.readerFailed(reader.error?.localizedDescription ?? "unknown")
        }
        progress(1)
    }

    // MARK: - Metadata helpers

    /// Builds a big-endian FourCC code from a 4-character string.
    private static func fourCC(_ string: String) -> UInt32 {
        string.utf8.reduce(UInt32(0)) { ($0 << 8) | UInt32($1) }
    }

    /// Creates the writer input/adaptor pair for the timed
    /// `mdta/com.apple.quicktime.still-image-time` metadata track.
    private static func makeStillImageTimeAdaptor() -> AVAssetWriterInputMetadataAdaptor? {
        let spec: [String: Any] = [
            kCMMetadataFormatDescriptionMetadataSpecificationKey_Identifier as String:
                "mdta/com.apple.quicktime.still-image-time",
            kCMMetadataFormatDescriptionMetadataSpecificationKey_DataType as String:
                kCMMetadataBaseDataType_SInt8 as String
        ]
        var formatDescription: CMFormatDescription?
        // FourCC 'stim' == kCMMetadataFormatDescriptionMetadataFormatType_StillImageTime,
        // which is not exposed to Swift by the SDK.
        let stillImageTimeFormatType = fourCC("stim")
        let status = CMMetadataFormatDescriptionCreateWithMetadataSpecifications(
            allocator: nil,
            metadataType: stillImageTimeFormatType,
            metadataSpecifications: [spec] as CFArray,
            formatDescriptionOut: &formatDescription
        )
        guard status == noErr, let formatDescription else { return nil }
        let input = AVAssetWriterInput(
            mediaType: .metadata,
            outputSettings: nil,
            sourceFormatHint: formatDescription
        )
        return AVAssetWriterInputMetadataAdaptor(assetWriterInput: input)
    }

    /// Appends one `still-image-time` sample (int8 = -1, i.e. 0xFF) at `time`.
    private static func appendStillImageTimeSample(
        adaptor: AVAssetWriterInputMetadataAdaptor,
        at time: CMTime
    ) {
        let item = AVMutableMetadataItem()
        item.keySpace = AVMetadataKeySpace(rawValue: "mdta")
        item.key = "com.apple.quicktime.still-image-time" as NSString
        item.dataType = kCMMetadataBaseDataType_SInt8 as String
        item.value = NSNumber(value: -1) // 0xFF — "this frame is the still photo"
        let group = AVTimedMetadataGroup(
            items: [item],
            timeRange: CMTimeRange(start: time, duration: CMTime(value: 1, timescale: 600))
        )
        adaptor.append(group)
    }

    /// File-level `mdta` metadata items replicating what an iPhone writes.
    private static func makeLivePhotoMetadataItems(options: PairingOptions) -> [AVMetadataItem] {
        func item(_ key: String, _ value: __owned NSCopying & NSObjectProtocol, dataType: String? = nil) -> AVMutableMetadataItem {
            let item = AVMutableMetadataItem()
            item.keySpace = AVMetadataKeySpace(rawValue: "mdta")
            item.key = key as NSString
            item.value = value
            if let dataType { item.dataType = dataType }
            return item
        }

        var items: [AVMetadataItem] = [
            item("com.apple.quicktime.content.identifier",
                 options.contentIdentifier as NSString),
            item("com.apple.quicktime.live-photo.auto",
                 NSNumber(value: 1),
                 dataType: kCMMetadataBaseDataType_SInt8 as String),
            item("com.apple.quicktime.live-photo.vitality-score",
                 NSNumber(value: 1.0),
                 dataType: kCMMetadataBaseDataType_Float32 as String),
            item("com.apple.quicktime.live-photo.vitality-scoring-version",
                 NSNumber(value: 4),
                 dataType: kCMMetadataBaseDataType_SInt32 as String),
            item("com.apple.quicktime.full-frame-rate-playback-intent",
                 NSNumber(value: 1),
                 dataType: kCMMetadataBaseDataType_SInt8 as String)
        ]

        if let date = options.creationDate {
            let formatter = ISO8601DateFormatter()
            formatter.formatOptions = [.withInternetDateTime]
            items.append(item("com.apple.quicktime.creationdate",
                              formatter.string(from: date) as NSString))
        }
        return items
    }

    /// Reads the existing `com.apple.quicktime.content.identifier` of a video, if any.
    static func readVideoContentIdentifier(videoURL: URL) -> String? {
        let asset = AVURLAsset(url: videoURL)
        for item in asset.metadata {
            if item.commonKey == nil,
               let key = item.key as? String,
               key == "com.apple.quicktime.content.identifier",
               let value = item.stringValue {
                return value
            }
        }
        return nil
    }

    // MARK: - Validation

    /// Verifies that a written pair shares the expected content identifier.
    static func validate(
        photoURL: URL,
        videoURL: URL,
        expectedIdentifier: String
    ) -> (photoOK: Bool, videoOK: Bool) {
        let photoID = readPhotoContentIdentifier(imageURL: photoURL)
        let videoID = readVideoContentIdentifier(videoURL: videoURL)
        return (photoID == expectedIdentifier, videoID == expectedIdentifier)
    }
}
